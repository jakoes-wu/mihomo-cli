def _ex(*lines: str) -> Tuple[str, str]:
    # click 会重排 epilog 段落；"\b" 段首标记让示例按原样逐行显示。
    body = "\n".join("  " + ln for ln in lines)
    return ("\b\n示例：\n" + body, "\b\nExamples:\n" + body)


