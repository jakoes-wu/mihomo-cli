"""由 state 生成 mihomo 的 config.yaml（方案 5.1.4）。

所有重载、重写（切模式、改镜像、preflight 暂停 TUN）都必须经过这里的同一个 render，
doctor D04 也按同一规则重新生成后比对，所以这里不得读取 state 以外的任何运行时信息。
"""

from __future__ import annotations

import os
from typing import Any, Dict, List, Optional

import yaml

from . import nodes as nodes_mod
from .state import Paths

GITHUB = "https://github.com"
HEALTH_URL = "https://www.gstatic.com/generate_204"
TUN_DEVICE = "mihomocli0"
HEADER = "# 本文件由 mihomo-cli 生成，手改会被覆盖 / generated by mihomo-cli, manual edits will be overwritten\n"

# TUN 生效时内核自己的 DNS 上游写死为公网地址：系统解析此时已指向 mihomo 自身，
# 用 system / dhcp:// 会形成循环（方案 5.1.8）。default-nameserver 必须是纯 IP。
DNS_DEFAULT_NAMESERVER = ["223.5.5.5", "119.29.29.29"]
DNS_PROXY_SERVER_NAMESERVER = ["https://223.5.5.5/dns-query"]
DNS_NAMESERVER = ["https://1.1.1.1/dns-query", "https://8.8.8.8/dns-query"]
DNS_CN_NAMESERVER = ["https://223.5.5.5/dns-query", "https://doh.pub/dns-query"]


def site_base(state: Dict[str, Any]) -> str:
    """下载站根地址：state.mirror 或 GitHub；写入 state 时已去掉末尾 /（方案 5.1.5）。"""
    return (state.get("mirror") or GITHUB).rstrip("/")


def geodata_url(state: Dict[str, Any], filename: str) -> str:
    return "%s/MetaCubeX/meta-rules-dat/releases/download/latest/%s" % (site_base(state), filename)


def tun_effective_in_config(state: Dict[str, Any]) -> bool:
    """配置里是否写 TUN：开关为真且未被开机冲突暂停（方案 5.1.7）。"""
    return bool(state.get("tun")) and not state.get("tun_suspended")


def active_profile(state: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    name = state.get("active_profile")
    if not name:
        return None
    return state["profiles"].get(name)


def provider_names(state: Dict[str, Any]) -> List[str]:
    """实际写出的 provider：自建 VPS 类没有 main，手工节点为空时没有 manual（方案 5.1.4）。"""
    prof = active_profile(state)
    if prof is None:
        return []
    names = []
    if prof["kind"] in ("subscription", "file"):
        names.append("main")
    if prof["manual"]:
        names.append("manual")
    return names


def expects_no_nodes(state: Dict[str, Any], main_names: Optional[List[str]] = None) -> bool:
    """按 state 判断 PROXY 组是否本来就该没有节点（只剩 REJECT）。

    main_names 为订阅 / 本地文件的当前节点名（从接口取得）；不知道时传 None，
    此时订阅类一律按“应有节点”处理。重载核验与 _service-reapply 的就绪判据共用本函数（方案 5.1.5）。
    """
    prof = active_profile(state)
    if prof is None:
        return True
    if prof["manual"]:
        return False
    if prof["kind"] == "nodes":
        return True
    if main_names is None:
        return False
    hidden = set(prof["hidden"])
    return all(name in hidden for name in main_names)


def render(state: Dict[str, Any], paths: Paths) -> Dict[str, Any]:
    prof = active_profile(state)
    profile_name = state.get("active_profile")
    cfg: Dict[str, Any] = {
        "mixed-port": int(state["mixed_port"]),
        "bind-address": "127.0.0.1",
        "allow-lan": False,
        "mode": state["mode"],
        "log-level": "info",
        # 关闭 TCP 管理端口，只用主目录下的 unix 套接字（方案 §6）。
        "external-controller": "",
        "external-controller-unix": os.path.basename(paths.sock),
        "profile": {"store-selected": True},
    }
    if state.get("mirror"):
        cfg["geox-url"] = {
            "geoip": geodata_url(state, "geoip.dat"),
            "mmdb": geodata_url(state, "geoip.metadb"),
            "asn": geodata_url(state, "GeoLite2-ASN.mmdb"),
            "geosite": geodata_url(state, "geosite.dat"),
        }

    providers: Dict[str, Any] = {}
    if prof is not None:
        health = {"enable": True, "url": HEALTH_URL, "interval": 600, "lazy": True}
        if prof["kind"] == "subscription":
            main: Dict[str, Any] = {
                "type": "http",
                "url": prof["url"],
                "path": "./providers/%s.yaml" % profile_name,
                "interval": int(prof.get("interval") or 86400),
                "health-check": health,
            }
            if prof.get("user_agent"):
                main["header"] = {"User-Agent": [prof["user_agent"]]}
            providers["main"] = main
        elif prof["kind"] == "file":
            providers["main"] = {
                "type": "file",
                "path": "./providers/%s.yaml" % profile_name,
                "health-check": health,
            }
        if prof["manual"]:
            providers["manual"] = {
                "type": "file",
                "path": "./nodes/%s.txt" % profile_name,
                "override": {"additional-prefix": nodes_mod.MANUAL_PREFIX},
            }
    if providers:
        cfg["proxy-providers"] = providers

    # PROXY 固定带 REJECT：mihomo 的空策略组会回落到 COMPATIBLE（即直连），
    # 加了 REJECT 组永不为空，没节点时表现为断网而不是悄悄直连（方案 5.1.4）。
    proxy_group: Dict[str, Any] = {
        "name": "PROXY",
        "type": "select",
        "use": provider_names(state),
        "proxies": ["REJECT"],
    }
    if prof is not None:
        flt = nodes_mod.hidden_filter(prof["hidden"])
        if flt:
            proxy_group["exclude-filter"] = flt
    groups: List[Dict[str, Any]] = [
        proxy_group,
        {"name": "CN", "type": "select", "proxies": ["DIRECT", "PROXY"]},
        # 显式定义 GLOBAL：内核自动生成的 GLOBAL 首个成员是 DIRECT，冷启动全局模式会整机直连（方案 5.1.4）。
        {"name": "GLOBAL", "type": "select", "proxies": ["PROXY"]},
    ]
    if os.environ.get("MIHOMO_CLI_TEST_BAD_CONFIG") == "1":
        # 测试注入（R-10）：未知组类型让 mihomo -t 报 unsupported type。
        groups.append({"name": "BAD", "type": "no-such-type", "proxies": ["DIRECT"]})
    cfg["proxy-groups"] = groups
    cfg["rules"] = [
        "GEOSITE,private,DIRECT",
        "GEOIP,private,DIRECT,no-resolve",
        "GEOSITE,cn,CN",
        "GEOIP,CN,CN",
        "MATCH,PROXY",
    ]

    if tun_effective_in_config(state):
        cfg["tun"] = {
            "enable": True,
            "device": TUN_DEVICE,
            "stack": "mixed",
            "auto-route": True,
            "auto-detect-interface": True,
            "dns-hijack": ["any:53"],
        }
        cfg["dns"] = {
            "enable": True,
            "listen": "127.0.0.1:53",
            "enhanced-mode": "fake-ip",
            "fake-ip-range": "198.18.0.1/16",
            "default-nameserver": list(DNS_DEFAULT_NAMESERVER),
            "proxy-server-nameserver": list(DNS_PROXY_SERVER_NAMESERVER),
            "nameserver": list(DNS_NAMESERVER),
            "nameserver-policy": {"geosite:cn,private": list(DNS_CN_NAMESERVER)},
        }
    return cfg


def render_text(state: Dict[str, Any], paths: Paths) -> str:
    body = yaml.safe_dump(render(state, paths), allow_unicode=True, sort_keys=False, default_flow_style=False)
    return HEADER + body
